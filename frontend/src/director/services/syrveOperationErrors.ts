export function syrveOperationError(cause: unknown, fallback: string): string {
  if (!cause || typeof cause !== 'object') return fallback;
  const { code, message } = cause as { code?: unknown; message?: unknown };
  if (typeof code === 'string' && Object.prototype.hasOwnProperty.call(CODE_MESSAGES, code)) {
    return CODE_MESSAGES[code];
  }
  return typeof message === 'string' && PUBLIC_MESSAGES.has(message) ? message : fallback;
}
